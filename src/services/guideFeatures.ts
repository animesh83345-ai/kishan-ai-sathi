export function findGuideFeature(query: string): GuideFeature | undefined {
  const normalized = query.trim().toLocaleLowerCase();
  if (!normalized) return undefined;
  const matches = GUIDE_FEATURES.flatMap((feature, index) => {
    const terms = [feature.title, feature.titleHi, ...feature.keywords]
      .map(term => term.toLocaleLowerCase())
      .filter(term => term.length > 1 && normalized.includes(term));
    return terms.length
      ? [{ feature, index, score: Math.max(...terms.map(term => term.length)) }]
      : [];
  });
  return matches.sort((left, right) => right.score - left.score || left.index - right.index)[0]?.feature;
}
